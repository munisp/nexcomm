#!/usr/bin/env node
/**
 * Generate Helm overrides for a secured staging rollout from CI-resolved image
 * digests. The input JSON must map every enabled Helm service key to a full
 * immutable OCI reference such as ghcr.io/acme/nexcom-exchange@sha256:<64 hex>.
 *
 * Usage:
 *   node scripts/generate-staging-digest-values.mjs image-digests.json generated-digests.yaml
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const requiredServices = [
  "nexcomExchange",
  "matchingEngine",
  "tradingEngine",
  "riskManagement",
  "kycService",
  "amlAlertSubscriber",
  "analyticsEngine",
  "analytics",
  "aiMl",
  "blockchain",
  "botLogic",
  "channelGateway",
  "coreBanking",
  "creditScoring",
  "cryptoGuard",
  "ddosGuard",
  "fluvioSidecar",
  "fraudEngine",
  "indices",
  "ingestionEngine",
  "marketData",
  "middlewareHub",
  "mojaloopAdapter",
  "notification",
  "opensearchSync",
  "pbac",
  "temporalWorkers",
  "userManagement",
  "ussdEngine",
];

const [inputPath, outputPath] = process.argv.slice(2);
if (!inputPath || !outputPath) {
  throw new Error("Usage: node scripts/generate-staging-digest-values.mjs <image-digests.json> <generated-values.yaml>");
}

const images = JSON.parse(readFileSync(resolve(inputPath), "utf8"));
if (!images || Array.isArray(images) || typeof images !== "object") {
  throw new Error("Image digest input must be a JSON object keyed by Helm service name");
}

const immutableReference = /^(?:[a-z0-9]+(?:[._-][a-z0-9]+)*(?::[0-9]+)?\/)+[a-z0-9]+(?:[._-][a-z0-9]+)*@sha256:[a-f0-9]{64}$/;
const unexpected = Object.keys(images).filter((name) => !requiredServices.includes(name));
const missing = requiredServices.filter((name) => !(name in images));
const invalid = requiredServices.filter((name) => typeof images[name] !== "string" || !immutableReference.test(images[name]));

if (unexpected.length || missing.length || invalid.length) {
  const details = [
    unexpected.length ? `unexpected keys: ${unexpected.join(", ")}` : "",
    missing.length ? `missing services: ${missing.join(", ")}` : "",
    invalid.length ? `invalid immutable references: ${invalid.join(", ")}` : "",
  ].filter(Boolean).join("; ");
  throw new Error(`Refusing to generate staging values: ${details}`);
}

const lines = [
  "# Generated by scripts/generate-staging-digest-values.mjs. Do not edit.",
  "global:",
  "  requireImageDigest: true",
  "  imagePullPolicy: Always",
];
for (const service of requiredServices) {
  lines.push(`${service}:`, "  image:", `    name: ${images[service]}`);
}
writeFileSync(resolve(outputPath), `${lines.join("\n")}\n`, { mode: 0o600 });
console.log(`Generated immutable staging image overrides for ${requiredServices.length} services: ${outputPath}`);
